"""
Partner collected data: template, validation, training and scoring.

    python -m tools.partner_data template --out data/external/partner_example [--mode fault_labels]
    python -m tools.partner_data validate --root data/external/partner
    python -m tools.partner_data train    --root data/external/partner [--model models/partner.joblib]
    python -m tools.partner_data score    --root data/external/new_batch --model models/partner.joblib

template  writes a complete example dataset (dataset.json, recordings.csv and
          CSV files) with telemetry, accelerometer, motor current and power, so
          the expected format can be copied exactly. The signals are SYNTHETIC.
validate  checks files, columns, timestamps, missing values, labels and runs
train     extracts window features and trains the models that label_mode allows
score     applies saved models to a new dataset folder with the same channels
"""

